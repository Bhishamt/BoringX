// Builds the tool registry from src/tools/*.tsx. Adding tool 41 = adding one file there.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { CATEGORIES, type ToolMeta } from "../src/engine/types";

async function main() {
const dir = path.resolve("src/tools");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".tsx")).sort();
const metas: ToolMeta[] = [];
const withBlocks: string[] = [];

for (const f of files) {
  const mod = await import(pathToFileURL(path.join(dir, f)).href);
  const meta: ToolMeta | undefined = mod.meta;
  if (!meta) throw new Error(`${f} must export \`meta\``);
  if (typeof mod.default !== "function") throw new Error(`${f} must default-export a component`);
  const slug = path.basename(f, ".tsx");
  if (meta.slug !== slug) throw new Error(`${f}: meta.slug "${meta.slug}" must equal the file name`);
  if (!CATEGORIES.includes(meta.category)) throw new Error(`${f}: unknown category ${meta.category}`);
  if (Array.isArray(mod.blocks) && mod.blocks.length) withBlocks.push(slug);
  metas.push(meta);
}
const slugs = new Set<string>();
for (const m of metas) { if (slugs.has(m.slug)) throw new Error(`duplicate slug ${m.slug}`); slugs.add(m.slug); }
metas.sort((a, b) => CATEGORIES.indexOf(a.category) - CATEGORIES.indexOf(b.category) || a.name.localeCompare(b.name));

fs.mkdirSync("src/generated", { recursive: true });
fs.writeFileSync("src/generated/tools.json", JSON.stringify(metas, null, 2) + "\n");
fs.writeFileSync(
  "src/generated/loaders.ts",
  `// generated by scripts/gen-registry.ts. Do not edit.\nimport type { ComponentType } from "react";\nexport const loaders: Record<string, () => Promise<{ default: ComponentType }>> = {\n${metas.map((m) => `  "${m.slug}": () => import("../tools/${m.slug}"),`).join("\n")}\n};\n`,
);
fs.writeFileSync(
  "src/generated/blocks.ts",
  `// generated by scripts/gen-registry.ts. Do not edit.\nimport type { BlockDef } from "../engine/types";\n${withBlocks.map((s, i) => `import { blocks as b${i} } from "../tools/${s}";`).join("\n")}\nexport const toolBlocks: BlockDef[] = [${withBlocks.map((_, i) => `...b${i}`).join(", ")}];\n`,
);
console.log(`registry: ${metas.length} tools, ${withBlocks.length} with blocks`);
}
main().catch((e) => { console.error(e); process.exit(1); });
