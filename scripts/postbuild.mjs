// After `next build` (static export to out/): write sitemap.xml and the offline service worker.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const out = path.resolve("out");
const SITE = process.env.SITE_URL || "https://boringx.vercel.app";
const tools = JSON.parse(fs.readFileSync("src/generated/tools.json", "utf8"));

const pages = ["", "sandbox", "about", "privacy", ...tools.map((t) => t.slug)];
fs.writeFileSync(path.join(out, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${pages.map((p) => `  <url><loc>${SITE}/${p}</loc></url>`).join("\n")}\n</urlset>\n`);

const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const rel = (f) => "/" + path.relative(out, f).split(path.sep).join("/");
const files = walk(out);
const pre = new Set(["/", "/sandbox", "/about", "/privacy", "/manifest.webmanifest", "/icon.svg", "/icon-192.png", "/apple-touch-icon.png", "/pdf.worker.min.mjs", "/workers/custom-js.js"]);
for (const t of tools) pre.add("/" + t.slug);
for (const f of files) { const r = rel(f); if (r.startsWith("/_next/static/") && !r.endsWith(".map")) pre.add(r); }
const list = [...pre].sort();
const version = crypto.createHash("sha1").update(list.map((u) => u + (fs.existsSync(path.join(out, u)) ? fs.statSync(path.join(out, u)).size : "")).join("|")).digest("hex").slice(0, 10);

fs.writeFileSync(path.join(out, "sw.js"), `// generated by scripts/postbuild.mjs
const CACHE = "boringx-${version}";
const PRECACHE = ${JSON.stringify(list)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => Promise.all(PRECACHE.map((u) => c.add(new Request(u, { cache: "reload" })).catch(() => {})))).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("boringx-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== location.origin || url.pathname === "/sw.js") return;
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try {
      const res = await fetch(req);
      if (res.ok && res.status === 200 && !req.headers.has("range")) cache.put(req, res.clone());
      return res;
    } catch (err) {
      if (req.mode === "navigate") { const home = await cache.match("/"); if (home) return home; }
      throw err;
    }
  })());
});
`);
console.log(`postbuild: sitemap (${pages.length} urls), sw.js (${list.length} precached, ${version})`);
